import { BehaviorType, PluginType, VarValue } from './types';

export type ParamInputType =
  | 'expression'
  | 'string'
  | 'number'
  | 'boolean'
  | 'key'
  | 'object'
  | 'globalVar'
  | 'instVar'
  | 'layout'
  | 'layer'
  | 'comparison'
  | 'select';

export interface ParamSchema {
  id: string;
  label: string;
  type: ParamInputType;
  defaultValue: string;
  options?: { value: string; label: string }[];
  placeholder?: string;
}

export interface ConditionSchema {
  id: string;
  name: string;
  category: string;
  description: string;
  isTrigger?: boolean;
  params: ParamSchema[];
  displayFormat: string; // e.g. "On collision with {other}"
}

export interface ActionSchema {
  id: string;
  name: string;
  category: string;
  description: string;
  params: ParamSchema[];
  displayFormat: string; // e.g. "Set X to {x}"
}

export interface BehaviorPropertySchema {
  key: string;
  label: string;
  type: 'number' | 'boolean' | 'select' | 'string';
  defaultValue: VarValue;
  options?: { value: string; label: string }[];
  min?: number;
  max?: number;
  step?: number;
}

export interface BehaviorCatalogEntry {
  type: BehaviorType;
  name: string;
  description: string;
  category: 'Movement' | 'Attributes' | 'General';
  properties: BehaviorPropertySchema[];
  conditions: ConditionSchema[];
  actions: ActionSchema[];
  expressions: { name: string; description: string; syntax: string }[];
}

export interface PluginCatalogEntry {
  plugin: PluginType;
  name: string;
  description: string;
  isVisual: boolean;
  conditions: ConditionSchema[];
  actions: ActionSchema[];
  expressions: { name: string; description: string; syntax: string }[];
}

